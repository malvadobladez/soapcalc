create table public.master_items (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(btrim(name)) > 0),
  item_class text not null default 'Other',
  category text,
  form text,
  is_active boolean not null default true,
  deprecated boolean not null default false,
  sap_naoh numeric(10,6),
  sap_koh numeric(10,6),
  fa_lauric numeric(10,4),
  fa_myristic numeric(10,4),
  fa_palmitic numeric(10,4),
  fa_stearic numeric(10,4),
  fa_ricinoleic numeric(10,4),
  fa_oleic numeric(10,4),
  fa_linoleic numeric(10,4),
  fa_linolenic numeric(10,4),
  iodine_value numeric(10,4),
  sap_source text,
  density_g_per_ml numeric(10,6),
  created_at timestamptz not null default now()
);
create table public.inventory_items (
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  master_item_id bigint not null references public.master_items(id),
  in_stock boolean not null default true,
  stock_quantity numeric check (stock_quantity >= 0),
  stock_unit text,
  purchase_total_cost numeric(10,2) check (purchase_total_cost >= 0),
  purchase_weight_grams numeric(10,3) check (purchase_weight_grams > 0),
  supplier text,
  purchase_note text,
  primary key (owner_id, master_item_id),
  check ((stock_quantity is null) = (stock_unit is null))
);
create index inventory_master_item_idx on public.inventory_items (master_item_id);
alter table public.master_items enable row level security;
alter table public.inventory_items enable row level security;
revoke all on public.master_items, public.inventory_items from anon, authenticated;
grant select on public.master_items to authenticated;
grant select, insert, update, delete on public.inventory_items to authenticated;
create policy "Signed-in users read the catalog" on public.master_items for select to authenticated using (true);
create policy "Owners manage their inventory" on public.inventory_items for all to authenticated
using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));
